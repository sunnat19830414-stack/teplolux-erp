/** Классификация одной строки: [группа, подгруппа] или null. */
function classify(array $p, array $rules): ?array
{
    $label = mb_strtolower((string)$p['label']);
    $label = str_replace(['-', '"', '«', '»', '.', ',', '/'], ' ', $label);
    $label = preg_replace('/\s+/u', ' ', $label);
    foreach ($rules as $rule) {
        if (preg_match('/' . $rule['w'] . '/u', $label)) return [$rule[0], $rule[1]];
    }
    return null;
}

$byPath = []; $unmatched = [];
foreach ($rows as $p) {
    $c = classify($p, $RULES);
    if ($c === null) { $unmatched[] = $p; continue; }
    $byPath[$c[0]][$c[1]][] = $p;
}

$total = count($rows); $matched = $total - count($unmatched);
printf("товаров: %d, распознано: %d (%d%%), не распознано: %d\n\n",
    $total, $matched, round($matched * 100 / $total), count($unmatched));

function dirs_of(array $items): string
{
    $d = ['J' => 0, 'T' => 0];
    foreach ($items as $i) { $k = substr((string)$i['kod_sap'], 0, 1); if (isset($d[$k])) $d[$k]++; }
    return sprintf('Ж %-4d Т %-4d', $d['J'], $d['T']);
}

