// ─────────────────────────────────────────────────────────────────────────────
// Создание дерева и привязка. Категории товаров: llx_categorie.type = 0.
// Существующие категории брендов не трогаем — товар лежит и там, и тут.
// ─────────────────────────────────────────────────────────────────────────────
$db->begin_transaction();
try {
    $created = 0; $linked = 0; $already = 0;

    /** Найти или создать категорию; $parent = 0 для корня. */
    $ensure = function (string $label, int $parent) use ($db, &$created): int {
        $st = $db->prepare("SELECT rowid FROM llx_categorie WHERE type = 0 AND label = ? AND fk_parent = ?");
        $st->bind_param('si', $label, $parent); $st->execute();
        $row = $st->get_result()->fetch_assoc(); $st->close();
        if ($row) return (int)$row['rowid'];

        $desc = 'Тип товара. Создано автоматически 10.09.2026 по названиям; бренды — отдельный разрез.';
        $st = $db->prepare("INSERT INTO llx_categorie (entity, label, description, type, fk_parent, visible, date_creation)
                            VALUES (1, ?, ?, 0, ?, 1, NOW())");
        $st->bind_param('ssi', $label, $desc, $parent); $st->execute();
        $id = (int)$db->insert_id; $st->close();
        $created++;
        return $id;
    };

    $link = $db->prepare("INSERT IGNORE INTO llx_categorie_product (fk_categorie, fk_product) VALUES (?, ?)");
    foreach ($byPath as $g => $subs) {
        $gid = $ensure($g, 0);
        foreach ($subs as $s => $items) {
            $sid = $ensure($s, $gid);
            foreach ($items as $it) {
                $pid = (int)$it['rowid'];
                // товар кладём и в подгруппу, и в корневую группу: тогда «Арматура» покажет всё
                foreach ([$sid, $gid] as $cid) {
                    $link->bind_param('ii', $cid, $pid);
                    $link->execute();
                    if ($link->affected_rows > 0) $linked++; else $already++;
                }
            }
        }
    }
    $link->close();
    $db->commit();
    printf("\nсоздано категорий: %d, новых привязок: %d, уже были: %d\n", $created, $linked, $already);
} catch (Throwable $e) {
    $db->rollback();
    fwrite(STDERR, "ОТКАТ: " . $e->getMessage() . "\n");
    exit(1);
}
