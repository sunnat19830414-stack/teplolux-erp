<?php
/**
 * Пересчёт себестоимости в момент ФИЗИЧЕСКОЙ приёмки (H4 финансового аудита 05.09.2026).
 *
 * ⚠️ Что было не так. Себестоимость с логистикой считалась в момент ВВОДА расхода. Если Нодир
 * вносил фрахт, пока груз ещё в пути (обычный порядок его работы), происходило вот что:
 *   1. расход внесён → `logistics_recompute_cost()` записывает в `pmp` правильную цифру с фрахтом;
 *   2. приходит машина, кассир делает приёмку → Dolibarr штатным механизмом усредняет `pmp`
 *      ЗАНОВО, уже с СЫРОЙ закупочной ценой строки заказа (без логистики) — и вклад фрахта
 *      размывается.
 * Воспроизведено на реальных числах: остаток 2 шт по $10 + заказ 10 шт по $10 + фрахт $20 →
 * должно быть 11.6667/шт, после приёмки получалось 10.2778/шт. **Из 20 $ фрахта терялось 16.67 $.**
 *
 * Что делаем: после успешной приёмки повторяем пересчёт — он ложится ПОВЕРХ того, что записал
 * Dolibarr, и восстанавливает правильную цифру. Базовая точка (`llx_supplier_landed_baseline`) при
 * этом уже зафиксирована и не пересоздаётся, поэтому вклад поставки не задваивается — именно ради
 * этого она и заводилась.
 *
 * Расчёт живёт в NodirTool (это его предметная область) — здесь только вызов. Путь берётся из
 * `config/shared.php`, чтобы при переезде на VPS правился один параметр, а не код.
 */

/**
 * Пересчитать себестоимость по заказу после приёмки.
 *
 * Возвращает ['ok'=>bool, 'note'=>string] — 'note' пустая, если пересчитывать было нечего.
 * Никогда не бросает исключений: приёмка уже состоялась, и ошибка пересчёта не должна её ломать.
 */
function recompute_landed_cost_after_receipt(array $cfg, int $orderId): array
{
    $path = $cfg['nodirtool_logistics_path'] ?? 'C:\\NodirTool\\includes\\logistics.php';
    if (!is_file($path)) {
        return ['ok' => false, 'note' => 'Не найден модуль расчёта себестоимости — сообщите Суннату.'];
    }

    try {
        require_once $path;

        // Пересчитываем ТОЛЬКО если по этой поставке реально есть логистические расходы. Иначе
        // трогать pmp нельзя: без расходов пересчёт считал бы по ЗАКАЗАННОМУ количеству, а Dolibarr
        // при частичной приёмке уже записал честную цифру по фактически принятому.
        if (!logistics_has_expenses_for_order($orderId)) {
            return ['ok' => true, 'note' => ''];
        }

        $res = logistics_recompute_cost('order', $orderId);
        $n = count($res['affected_products'] ?? []);
        return ['ok' => true, 'note' => $n > 0
            ? "Себестоимость пересчитана с учётом логистики (позиций: {$n})."
            : ''];
    } catch (Throwable $e) {
        return ['ok' => false, 'note' => 'Себестоимость не пересчиталась (' . $e->getMessage()
            . ') — товар принят, но логистика в неё не вошла. Сообщите Суннату.'];
    }
}
