<?php
/**
 * S-1 (внешний QA-аудит, раунд 2, 03.09.2026): TeplouxKassa и NodirTool раньше делили ОДНУ сессию —
 * браузер не различает localhost:8010/:8011 по порту (порт не входит в область действия cookie), а
 * оба приложения использовали дефолтное имя cookie PHPSESSID И дефолтный session.gc_maxlifetime
 * (1440 сек = 24 мин.). Из-за этого: вход в одно приложение "перетирал" сессию другого (общий
 * PHPSESSID → session_regenerate_id() здесь уничтожал файл сессии NodirTool), выход из одного
 * разлогинивал оба сразу, а сборщик мусора PHP, запущенный запросом К ЭТОМУ приложению, мог вычищать
 * из ОБЩЕГО каталога сессий даже "восьмичасовые" сессии NodirTool (та настройка привязана к
 * ТЕКУЩЕМУ значению gc_maxlifetime на момент сборки мусора — если кассa не поднимала его у себя, её
 * же запросы понижали фактический эффект для соседнего приложения).
 *
 * `session_name()` ниже даёт TeplouxKassa СОБСТВЕННОЕ имя cookie, отличное от NodirTool (см. её
 * includes/session_boot.php) — теперь оба приложения физически хранят РАЗНЫЕ сессии, даже деля один
 * и тот же браузер/хост. gc_maxlifetime поднят до того же 1 рабочего дня, что и у NodirTool — кассиры
 * тоже работают полную смену, не должны разлогиниваться посреди дня из-за сборки мусора.
 *
 * ОБЯЗАТЕЛЬНО подключать ДО session_start() — и в login.php (там сессия создаётся), и в
 * includes/auth.php (там же продолжается на каждой следующей странице) — иначе настройка не подействует
 * на уже созданную сессию.
 */
const TEPLOUXKASSA_SESSION_LIFETIME = 8 * 3600;
session_name('TEPLOUXKASSASESSID');
ini_set('session.gc_maxlifetime', (string)TEPLOUXKASSA_SESSION_LIFETIME);
session_set_cookie_params(TEPLOUXKASSA_SESSION_LIFETIME);
