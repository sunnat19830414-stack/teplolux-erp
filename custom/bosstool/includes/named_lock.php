<?php
/**
 * Именованная блокировка на время «проверил — записал» (финансовый аудит 05.09.2026).
 *
 * Зачем именно MySQL `GET_LOCK`, а не сессия или файл: IIS/FastCGI обрабатывает параллельные
 * запросы РАЗНЫМИ процессами без общей памяти, а сессия к тому же у направления одна на всех
 * (Жамшид может работать с двух вкладок или двух устройств под общим паролем). Блокировка на
 * стороне сервера БД — единственное, что видно всем процессам сразу.
 *
 * Почему это оказалось не теоретическим: живые тесты аудита показали реальное задвоение денег в
 * 50–75% попыток при двух почти одновременных нажатиях кнопки. Отдельно неприятно, что
 * `Facture::setPaid()` в Dolibarr ИДЕМПОТЕНТЕН — повторный вызов на уже закрытый документ тоже
 * отвечает «успех», поэтому «проверка, что документ ещё открыт» сама по себе гонку не ловит.
 *
 * Ключ выбирается как можно уже (конкретный клиент/счёт/сотрудник), чтобы параллельная работа по
 * РАЗНЫМ объектам не выстраивалась в очередь.
 *
 * Копия этого файла лежит в обоих инструментах (как xls_helper.php) — правки вносить в оба.
 */

/**
 * Выполнить $fn под блокировкой $key. Возвращает результат $fn либо
 * ['ok'=>false,'error'=>...], если блокировку не удалось взять за $timeout секунд.
 *
 * $fn должен содержать И проверку, И саму запись — иначе смысла в блокировке нет.
 */
function with_named_lock(string $key, callable $fn, int $timeout = 10)
{
    $dbCfg = require __DIR__ . '/../config/db.local.php';
    $db = new mysqli($dbCfg['host'], $dbCfg['user'], $dbCfg['pass'], $dbCfg['name']);
    if ($db->connect_errno) {
        return ['ok' => false, 'error' => 'Не удалось подключиться к БД для блокировки: ' . $db->connect_error];
    }
    // Имя блокировки в MySQL ограничено 64 символами — длинные ключи сворачиваем в хэш.
    $name = strlen($key) > 60 ? 'lk_' . md5($key) : $key;
    $escaped = $db->real_escape_string($name);

    $res = $db->query("SELECT GET_LOCK('{$escaped}', " . (int)$timeout . ") AS got");
    $row = $res ? $res->fetch_assoc() : null;
    if (!$row || (int)$row['got'] !== 1) {
        $db->close();
        return ['ok' => false, 'error' => 'Эта же операция сейчас выполняется в другом окне — подождите несколько секунд и повторите.'];
    }
    try {
        return $fn();
    } finally {
        $db->query("SELECT RELEASE_LOCK('{$escaped}')");
        $db->close();
    }
}

/**
 * Взять блокировку и держать её ДО КОНЦА ЗАПРОСА.
 *
 * Нужно там, где критичный участок заканчивается редиректом с `exit` — при `exit` блок `finally`
 * в PHP не выполняется, поэтому обёртка с callback'ом там неудобна. MySQL сам снимает именованные
 * блокировки при закрытии соединения, а оно закрывается вместе с запросом, — так что «забыть
 * освободить» здесь невозможно. Соединение специально держится в статической переменной: закройся
 * оно раньше, блокировка снялась бы вместе с ним.
 *
 * Возвращает true, если блокировка взята.
 */
function acquire_named_lock(string $key, int $timeout = 10): bool
{
    $held = &named_lock_registry();
    if (isset($held[$key])) return true;   // уже держим в этом же запросе

    $dbCfg = require __DIR__ . '/../config/db.local.php';
    $conn = new mysqli($dbCfg['host'], $dbCfg['user'], $dbCfg['pass'], $dbCfg['name']);
    if ($conn->connect_errno) return false;

    $name = strlen($key) > 60 ? 'lk_' . md5($key) : $key;
    $res = $conn->query("SELECT GET_LOCK('" . $conn->real_escape_string($name) . "', " . (int)$timeout . ") AS got");
    $row = $res ? $res->fetch_assoc() : null;
    if (!$row || (int)$row['got'] !== 1) {
        $conn->close();
        return false;
    }
    $held[$key] = $conn;   // держим соединение живым — вместе с ним живёт и блокировка
    return true;
}

/**
 * Снять блокировку раньше конца запроса. Веб-страницам это не нужно (там всё снимается само при
 * завершении запроса), но нужно долгоживущим скриптам — проверочным и разовым: иначе один процесс
 * держит блокировку до самого конца и блокирует сам себя, а заодно и реальных пользователей.
 */
function release_named_lock(string $key): void
{
    $held = &named_lock_registry();
    if (!isset($held[$key])) return;
    $held[$key]->close();
    unset($held[$key]);
}

/** Соединения, которые держат взятые блокировки. Одно на весь запрос. */
function &named_lock_registry(): array
{
    static $held = [];
    return $held;
}
