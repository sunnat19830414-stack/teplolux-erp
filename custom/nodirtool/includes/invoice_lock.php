<?php
/**
 * N-2 (внешний QA-аудит, раунд 2, 03.09.2026) — защита от двойной оплаты счёта поставщику при
 * одновременном нажатии "Оплатить" двумя закупщиками (Нодир и Абдурашид видят обоих поставщиков и
 * иногда подменяют друг друга — реальный, не гипотетический сценарий). Раньше проверка остатка
 * ("сколько ещё можно заплатить") и сама запись платежа шли БЕЗ блокировки между ними — два
 * параллельных запроса оба успевали прочитать один и тот же остаток ДО того, как хоть один успевал
 * записать свой платёж, и оба проходили. Используем MySQL `GET_LOCK()` — именованная блокировка на
 * уровне СЕРВЕРА БД (не PHP-сессии/файла — те не годятся, IIS/FastCGI обрабатывает разные запросы
 * РАЗНЫМИ процессами без общей памяти), keyed по id счёта, так что параллельны только платежи по
 * РАЗНЫМ счетам, а не вообще все оплаты сразу.
 */

/**
 * Выполнить $fn, держа именованную блокировку MySQL на конкретный счёт поставщику. Возвращает то, что
 * вернул $fn, либо ['ok'=>false,'error'=>'...'] если лок не удалось получить за разумное время (кто-то
 * уже платит по этому же счёту прямо сейчас).
 */
function nt_with_supplier_invoice_lock(int $invoiceId, callable $fn)
{
    // 05.09.2026: сама механика переехала в includes/named_lock.php — она понадобилась ещё в трёх
    // местах (выдача денег, возврат по счёту, начисление зарплаты). Здесь остался только ключ.
    require_once __DIR__ . '/named_lock.php';
    return with_named_lock('nodirtool_supplier_invoice_' . $invoiceId, $fn);
}
