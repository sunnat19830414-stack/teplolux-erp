/**
 * Сумма прописью по-русски — для спецификации поставщику (пункт B1 отчёта «Пробелы NodirTool»,
 * 04.09.2026). В каждой реальной спецификации Теплолюкс такая строка есть:
 *   «Итого: 117.832,91 (Сто семнадцать тысяч восемьсот тридцать два Евро, 91 Евроцентов) Евро.»
 * Без неё документ пришлось бы дописывать руками в Excel, то есть смысл выгрузки терялся бы.
 */

/** Согласование слова с числом: 1 рубль / 2 рубля / 5 рублей. */
function ntw_plural(int $n, string $one, string $few, string $many): string
{
    $n = abs($n) % 100;
    if ($n >= 11 && $n <= 19) return $many;
    $n %= 10;
    if ($n === 1) return $one;
    if ($n >= 2 && $n <= 4) return $few;
    return $many;
}

/**
 * Число (до триллиона) прописью. $female — для «тысяч» (одна, две) и для копеек.
 */
function ntw_number(int $number, bool $female = false): string
{
    if ($number === 0) return 'ноль';

    $units = [
        ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'],
        ['', 'одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'],
    ];
    $teens = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать',
              'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
    $tens = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят',
             'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
    $hundreds = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот',
                 'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];

    // Разряды: [название в трёх формах, женский ли род]
    $scales = [
        [['', '', ''], $female],
        [['тысяча', 'тысячи', 'тысяч'], true],
        [['миллион', 'миллиона', 'миллионов'], false],
        [['миллиард', 'миллиарда', 'миллиардов'], false],
        [['триллион', 'триллиона', 'триллионов'], false],
    ];

    // Разбиваем на группы по три цифры, младшая группа первой.
    $groups = [];
    $rest = abs($number);
    while ($rest > 0) {
        $groups[] = $rest % 1000;
        $rest = intdiv($rest, 1000);
    }

    $words = [];
    for ($i = count($groups) - 1; $i >= 0; $i--) {
        $g = $groups[$i];
        if ($g === 0) continue;
        [$scaleForms, $isFemale] = $scales[$i] ?? [['', '', ''], false];
        $u = $units[$isFemale ? 1 : 0];

        $h = intdiv($g, 100);
        $t = intdiv($g % 100, 10);
        $o = $g % 10;

        if ($h > 0) $words[] = $hundreds[$h];
        if ($t === 1) {
            $words[] = $teens[$o];
        } else {
            if ($t > 1) $words[] = $tens[$t];
            if ($o > 0) $words[] = $u[$o];
        }
        if ($scaleForms[0] !== '') {
            $words[] = ntw_plural($g, $scaleForms[0], $scaleForms[1], $scaleForms[2]);
        }
    }

    return implode(' ', array_filter($words));
}

/**
 * Денежная сумма прописью с названием валюты и разменной единицы.
 * Возвращает, например: «Сто семнадцать тысяч восемьсот тридцать два Евро, 91 Евроцент».
 * Разменную часть пишем цифрами — ровно как в существующих спецификациях Теплолюкс.
 */
function ntw_money(float $amount, string $currency = 'USD'): string
{
    $forms = [
        'USD' => [['доллар', 'доллара', 'долларов'], false, ['цент', 'цента', 'центов']],
        'EUR' => [['Евро', 'Евро', 'Евро'], false, ['Евроцент', 'Евроцента', 'Евроцентов']],
        'RUB' => [['рубль', 'рубля', 'рублей'], false, ['копейка', 'копейки', 'копеек']],
        'UZS' => [['сум', 'сума', 'сумов'], false, ['тийин', 'тийина', 'тийинов']],
    ];
    [$main, $female, $sub] = $forms[strtoupper($currency)] ?? $forms['USD'];

    $amount = round($amount, 2);
    $whole = (int)floor($amount);
    $cents = (int)round(($amount - $whole) * 100);
    if ($cents === 100) { $whole++; $cents = 0; }

    $text = ntw_number($whole, $female) . ' ' . ntw_plural($whole, $main[0], $main[1], $main[2]);
    $text .= ', ' . $cents . ' ' . ntw_plural($cents, $sub[0], $sub[1], $sub[2]);

    return mb_strtoupper(mb_substr($text, 0, 1)) . mb_substr($text, 1);
}
