<?php
/**
 * Единая настройка времени жизни сессии закупщика (UX-N1, внешний отчёт 02.09.2026) — раньше был
 * дефолтный session.gc_maxlifetime (1440 сек = 24 минуты), из-за чего сессия могла "отвалиться" прямо
 * в середине работы, если закупщик долго не совершал ни одного запроса (заполнение формы, чтение
 * документа, разговор с поставщиком по телефону и т.п.). Поднято до 8 часов (рабочий день).
 *
 * S-1 (внешний QA-аудит, раунд 2, 03.09.2026): TeplouxKassa и NodirTool раньше делили ОДНУ сессию —
 * браузер не различает localhost:8010/:8011 по порту (порт не входит в область действия cookie), а
 * оба приложения использовали дефолтное имя cookie PHPSESSID — вход в одно приложение "перетирал"
 * сессию другого, выход из одного разлогинивал оба сразу. `session_name()` ниже даёт NodirTool
 * СОБСТВЕННОЕ имя cookie, отличное от TeplouxKassa (см. её собственный includes/session_boot.php) —
 * теперь оба приложения физически хранят РАЗНЫЕ сессии, даже деля один и тот же браузер/хост.
 *
 * ОБЯЗАТЕЛЬНО подключать ДО session_start() — и в login.php (там сессия создаётся), и в
 * includes/auth.php (там же продолжается на каждой следующей странице) — иначе настройка не подействует
 * на уже созданную сессию.
 */
const NODIRTOOL_SESSION_LIFETIME = 8 * 3600;
session_name('NODIRTOOLSESSID');
ini_set('session.gc_maxlifetime', (string)NODIRTOOL_SESSION_LIFETIME);
session_set_cookie_params(NODIRTOOL_SESSION_LIFETIME);
