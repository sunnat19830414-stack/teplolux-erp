<?php
/**
 * Получить спецификацию заказа СТРОКОЙ, чтобы приложить её к письму (05.09.2026).
 *
 * ⚠️ Почему не HTTP-запросом к собственному spec_excel.php (так было в первой версии и это поймал
 * тест): PHP блокирует файл сессии на время запроса. Страница, которая уже держит сессию, дёргает
 * сама себя — и вторая половина ждёт освобождения, которого не будет, пока не закончится первая.
 * Получается взаимная блокировка: отправка «висела» до таймаута и молча оставалась без вложения.
 * Поэтому документ формируется прямо здесь, в том же процессе — тем же самым кодом, что и при
 * обычном скачивании, так что поставщик получает ровно тот файл, который закупщик видит у себя
 * (включая тот же самый, единожды присвоенный номер спецификации).
 */

function spec_render_to_string(int $orderId): ?string
{
    global $api, $cfg;                    // spec_excel.php работает с ними как с глобальными

    $savedGet = $_GET;
    $_GET['id'] = $orderId;
    $GLOBALS['SPEC_RETURN_MODE'] = true;

    ob_start();
    try {
        // include, а не require_once: за один запрос спецификация может понадобиться не единожды.
        include __DIR__ . '/../spec_excel.php';
        $out = ob_get_clean();
    } catch (Throwable $e) {
        ob_end_clean();
        $out = '';
    } finally {
        unset($GLOBALS['SPEC_RETURN_MODE']);
        $_GET = $savedGet;
    }

    return (is_string($out) && strlen($out) > 100) ? $out : null;
}
